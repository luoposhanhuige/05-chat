// # Difference: `ErrorOutput` vs Direct String

// You're right to question it. Let me show the difference:

// ## Current Code
// ```rust
// Json(ErrorOutput::new(self.to_string()))
// ```

// **Response:**
// ```json
// {
//   "error": "email already exists: test@example.com"
// }
// ```

// ## If You Remove `ErrorOutput`
// ```rust
// Json(self.to_string())
// ```

// **Response:**
// ```json
// "email already exists: test@example.com"
// ```

// ## Key Differences

// | Aspect | With `ErrorOutput` | Without |
// |--------|-------------------|---------|
// | **Structure** | JSON object with `error` field | Plain JSON string |
// | **Content-Type** | `application/json` object | `application/json` string |
// | **Client Parsing** | `response.error` | `response` (raw string) |
// | **Consistency** | Structured API contract | Less predictable |
// | **Extensibility** | Easy to add `code`, `details`, etc. | Harder to extend |

// ## Example Client Code

// **With `ErrorOutput`:**
// ```javascript
// const res = await fetch('/api/signup', ...);
// const data = await res.json();
// console.log(data.error); // "email already exists: test@example.com"
// ```

// **Without `ErrorOutput`:**
// ```javascript
// const res = await fetch('/api/signup', ...);
// const data = await res.json();
// console.log(data); // "email already exists: test@example.com"
// ```

// ## My Recommendation

// **Keep `ErrorOutput`.** It's a best practice because:

// 1. **Consistency** — Success responses are objects (`{ token: "..." }`), errors should be too
// 2. **Extensibility** — Later you might want to add error codes, timestamps, or detailed info:
//    ```rust
//    #[derive(Debug, Serialize, Deserialize)]
//    pub struct ErrorOutput {
//        pub error: String,
//        pub code: String,
//        pub timestamp: DateTime<Utc>,
//    }
//    ```
// 3. **API Contract** — Clients know to always extract from `.error` field

// If you remove it, you sacrifice a clean API design for minimal savings (wrapping a string in an object is trivial).
